#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_lines_at_glyph_size() {
        let image = text_image("Up\nE?é");
        assert_eq!((image.width(), image.height()), (3 * GLYPH_W, LINE_H + GLYPH_H));
        let data = image.data.as_ref().unwrap();
        let lit = |x: u32, y: u32| data[((y * image.width() + x) * 4 + 3) as usize] == 255;
        // 'E' (second line) has a full-width top bar from x=1 to x=4 on its row 1.
        assert!((1..5).all(|x| lit(x, LINE_H + 1)));
        // Unknown characters draw like '?'.
        let glyph = |col: u32| {
            (0..GLYPH_H)
                .flat_map(|y| (0..GLYPH_W).map(move |x| (x, y)))
                .map(|(x, y)| lit(col * GLYPH_W + x, LINE_H + y))
                .collect::<Vec<_>>()
        };
        assert_eq!(glyph(1), glyph(2));
        assert_eq!(text_width(""), 0);
        assert_eq!(text_image("").width(), 1);
    }
}
