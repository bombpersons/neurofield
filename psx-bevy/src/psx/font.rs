//! A 6×9 bitmap font for text drawn into the low-resolution PS1 canvas, where
//! vector fonts break up. PS1 games drew text from bitmap fonts in VRAM; this
//! is the same idea. Glyphs are the X11 misc-fixed 6x9 font (public domain),
//! printable ASCII only; other characters draw as `?`.
//!
//! [`text_image`] renders white pixels on transparency, so tint the result
//! with `ImageNode::color` or `Sprite::color`. Show it at its own size (one
//! texel per canvas pixel) to keep it sharp.

use bevy::prelude::*;

/// Advance per character, in pixels.
pub const GLYPH_W: u32 = 6;
/// Glyph height including descenders.
pub const GLYPH_H: u32 = 9;
/// Distance between lines of a multi-line string.
pub const LINE_H: u32 = 10;

/// Width in pixels of the longest line of `text`.
pub fn text_width(text: &str) -> u32 {
    text.lines().map(|l| l.chars().count() as u32).max().unwrap_or(0) * GLYPH_W
}

/// `text` as a white-on-transparent RGBA image; `\n` starts a new line.
pub fn text_image(text: &str) -> Image {
    let lines = text.split('\n').count() as u32;
    let (width, height) = (text_width(text).max(1), (lines - 1) * LINE_H + GLYPH_H);
    let mut rgba = vec![0u8; (width * height * 4) as usize];
    for (row, line) in text.split('\n').enumerate() {
        for (col, c) in line.chars().enumerate() {
            let glyph = GLYPHS[if (' '..='~').contains(&c) { c as usize - 32 } else { '?' as usize - 32 }];
            for (y, bits) in glyph.iter().enumerate() {
                for x in 0..GLYPH_W {
                    if bits >> (GLYPH_W - 1 - x) & 1 == 1 {
                        let (px, py) = (col as u32 * GLYPH_W + x, row as u32 * LINE_H + y as u32);
                        let i = ((py * width + px) * 4) as usize;
                        rgba[i..i + 4].copy_from_slice(&[255; 4]);
                    }
                }
            }
        }
    }
    super::rgba_image(width, height, rgba)
}

